
PRAGMA foreign_keys=ON;
CREATE TABLE product(
 CHANNEL TEXT NOT NULL, PROD_ID INTEGER NOT NULL, PROD_NAME TEXT NOT NULL,
 PRIMARY KEY(CHANNEL,PROD_ID)
);
CREATE TABLE tran(
 CHANNEL TEXT NOT NULL, TRAN_ID INTEGER NOT NULL, TRAN_NAME TEXT NOT NULL,
 PRIMARY KEY(CHANNEL,TRAN_ID)
);
CREATE TABLE prod_detl(
 CHANNEL TEXT NOT NULL, PROD_DETL_ID INTEGER NOT NULL, PROD_ID INTEGER NOT NULL, TRAN_ID INTEGER NOT NULL,
 FEE_GROUP_ID INTEGER NOT NULL, EXTRA_CMSN_ID INTEGER NOT NULL,
 PRIMARY KEY(CHANNEL,PROD_DETL_ID), UNIQUE(CHANNEL,PROD_ID,TRAN_ID)
);
CREATE TABLE group_fees_detl(
 CHANNEL TEXT NOT NULL, DETL_ID INTEGER NOT NULL, FEES_GROUP_ID INTEGER NOT NULL, FEES_ID INTEGER NOT NULL,
 PRIMARY KEY(CHANNEL,DETL_ID)
);
CREATE TABLE fee(
 CHANNEL TEXT NOT NULL, FEE_ID INTEGER NOT NULL, FEE_NAME TEXT NOT NULL, CRCY_TYPE_CODE TEXT NOT NULL,
 PRIMARY KEY(CHANNEL,FEE_ID)
);
CREATE TABLE fee_detl(
 CHANNEL TEXT NOT NULL, FEE_DETL_ID INTEGER NOT NULL, FEE_ID INTEGER NOT NULL,
 RNGE_STRT REAL NOT NULL, RNGE_END REAL NOT NULL, MIN_FEE REAL NOT NULL, MAX_FEE REAL NOT NULL,
 PCNT REAL NOT NULL, LQDTY TEXT NOT NULL,
 PRIMARY KEY(CHANNEL,FEE_DETL_ID)
);
CREATE TABLE zone(
 CHANNEL TEXT NOT NULL, ZONE_ID INTEGER NOT NULL, ZONE_CODE TEXT NOT NULL, ZONE_NAME TEXT NOT NULL,
 PRIMARY KEY(CHANNEL,ZONE_ID)
);
CREATE TABLE extra_commission(
 CHANNEL TEXT NOT NULL, EXTRA_CMSN_DETL_ID INTEGER NOT NULL, EXTRA_CMSN_ID INTEGER NOT NULL,
 ZONE_ID INTEGER NOT NULL, CURRENCY TEXT NOT NULL, EXTRA_CMSN_PRCNTG REAL NOT NULL,
 PRIMARY KEY(CHANNEL,EXTRA_CMSN_DETL_ID)
);
CREATE TABLE liquidity_type(CODE TEXT PRIMARY KEY, NAME TEXT UNIQUE NOT NULL);
CREATE TABLE liquidity_matrix(FROM_LQDTY TEXT NOT NULL, TO_LQDTY TEXT NOT NULL, CALCULATED_LQDTY TEXT NOT NULL, PRIMARY KEY(FROM_LQDTY,TO_LQDTY));
CREATE TABLE channel_config(CHANNEL TEXT PRIMARY KEY, DISPLAY_NAME TEXT NOT NULL, FOREIGN_FEE_LQDTY TEXT NOT NULL);
CREATE INDEX idx_pd ON prod_detl(CHANNEL,PROD_ID,TRAN_ID);
CREATE INDEX idx_group ON group_fees_detl(CHANNEL,FEES_GROUP_ID);
CREATE INDEX idx_fee ON fee(CHANNEL,CRCY_TYPE_CODE);
CREATE INDEX idx_fd ON fee_detl(CHANNEL,FEE_ID,LQDTY,RNGE_STRT,RNGE_END);
CREATE INDEX idx_extra ON extra_commission(CHANNEL,EXTRA_CMSN_ID,CURRENCY,ZONE_ID);
